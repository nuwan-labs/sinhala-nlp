def _verdict_badge(v):
    v = str(v).lower()
    if "restrict" in v and "negligible" not in v and "withdraw" not in v and "no " not in v:
        return f'<span class="ok">{esc(v)}</span>'
    if "present" in v or "carries signal" in v or "beyond-layout" in v.replace("_", " ") or "True" in str(v):
        return f'<span class="ok">{esc(v)}</span>'
    if "overlap" in v or "withdraw" in v or "no signal" in v or "equivalent" in v or "anti" in v:
        return f'<span class="warn">{esc(v)}</span>'
    return f'<span class="warn">{esc(v)}</span>'


