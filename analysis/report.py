def esc(x):
    return html.escape(str(x))


def fnum(x, n=3):
    try:
        if isinstance(x, bool):
            return str(x)
        return f"{float(x):.{n}f}"
    except (TypeError, ValueError):
        return esc(x)


def img(b64, alt=""):
    return f'<img alt="{esc(alt)}" style="max-width:100%;border:1px solid #ddd;margin:8px 0" src="data:image/png;base64,{b64}"/>'


def table(headers, rows, cls=""):
    h = "".join(f"<th>{esc(x)}</th>" for x in headers)
    body = []
    for r in rows:
        body.append("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>")
    return f'<table class="{cls}"><thead><tr>{h}</tr></thead><tbody>{"".join(body)}</tbody></table>'


